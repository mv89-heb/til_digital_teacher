def _blocks(title: str, explanation: str, example: str):
    return [
        (LessonSection.SIMPLE_EXPLANATION, f"{title}\n\n{explanation}"),
        (LessonSection.NORMAL_EXPLANATION, f"{explanation}\n\nהמפתח הוא לעבוד בצורה שיטתית ולא לנחש לפי תחושה."),
        (LessonSection.SOLVED_EXAMPLE, f"דוגמה פתורה:\n\n{example}\n\nבדקו שהתוצאה מתאימה לכל הנתונים."),
        (LessonSection.NORMAL_METHOD, "שיטת עבודה:\n1. קראו את הנתונים.\n2. זהו את סוג הבעיה.\n3. כתבו חוק או קשר קצר.\n4. פתרו צעד-צעד.\n5. בדקו מול האפשרויות."),
        (LessonSection.FAST_METHOD, "שיטה מהירה למבחן:\nחפשו קודם את המשתנה או הקשר שמסביר את רוב הנתונים. אל תפתרו יותר ממה שנדרש כדי להכריע בין האפשרויות."),
        (LessonSection.COMMON_MISTAKES, "טעויות נפוצות:\n• התחלת פתרון לפני הבנת החוק.\n• בחירת תשובה שנראית סבירה בלי בדיקה.\n• השקעת זמן רב מדי בפרט שאינו משפיע."),
        (LessonSection.SUMMARY, f"סיכום:\n{title}. {explanation} המטרה היא פתרון מדויק תוך שמירה על קצב."),
    ]


def seed_curriculum():
    created_categories = 0
    created_lessons = 0
    icons = {CategoryType.QUANTITATIVE: "calculator", CategoryType.VERBAL: "book-open", CategoryType.FIGURAL: "shapes", CategoryType.LOGIC: "brain"}
    for order, (category_type, payload) in enumerate(CURRICULUM.items(), start=1):
        category_name, category_description, lessons = payload
        category = Category.query.filter_by(name=category_name, type=category_type).first()
        if category is None:
            category = Category(name=category_name, description=category_description, type=category_type, icon=icons[category_type], status=ContentStatus.PUBLISHED, order=order)
            db.session.add(category)
            db.session.flush()
            created_categories += 1
        for index, (title, explanation, example) in enumerate(lessons, start=1):
            if Lesson.query.filter_by(slug=slugify(title)).first():
                continue
            difficulty = LessonDifficulty.BEGINNER if index <= 4 else LessonDifficulty.INTERMEDIATE if index <= 8 else LessonDifficulty.ADVANCED
            lesson = Lesson(category_id=category.id, title=title, slug=slugify(title), description=explanation, status=ContentStatus.PUBLISHED, difficulty_level=difficulty, estimated_duration=12 if difficulty == LessonDifficulty.BEGINNER else 15 if difficulty == LessonDifficulty.INTERMEDIATE else 18, icon="book-open", order=index)
            db.session.add(lesson)
            db.session.flush()
            for block_order, (section, body) in enumerate(_blocks(title, explanation, example), start=1):
                db.session.add(LessonContent(lesson_id=lesson.id, section=section, block_type=BlockType.TEXT, order=block_order, content={"format": "markdown", "body": body.strip()}, block_metadata={}))
            created_lessons += 1
    db.session.commit()
    return {"created_categories": created_categories, "created_lessons": created_lessons, "curriculum_lessons": sum(len(v[2]) for v in CURRICULUM.values())}
